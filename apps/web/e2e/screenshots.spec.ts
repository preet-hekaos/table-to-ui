import { expect, test } from '@playwright/test'

/** Captures the slice screens for the PR (docs/screens). Run: pnpm exec playwright test screenshots */
const run = Date.now().toString(36)
const out = (n: string) => `../../docs/screens/${n}.png`

test('capture slice screens', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/signup')
  await page.screenshot({ path: out('01-sign-up') })
  await page.getByLabel(/Workspace name/).fill(`Northstar Talent Partners ${run}`)
  await page.getByLabel(/Your name/).fill('Ananya Rao')
  await page.getByLabel(/Work email/).fill(`shots-${run}@northstar.test`)
  await page.getByLabel(/^Password/).fill('correct-horse-battery')
  await page.getByRole('button', { name: 'Create workspace' }).click()
  await page.screenshot({ path: out('01b-choose-pack') })
  await page.getByLabel(/Recruitment agency/).check()
  await page.getByRole('button', { name: 'Set up workspace' }).click()
  await expect(page.getByRole('navigation', { name: 'Main' })).toBeVisible()
  await page.screenshot({ path: out('02-home') })
  await page.goto('/studio')
  await page.screenshot({ path: out('03-studio-data') })
  await page.getByRole('tab', { name: 'Versions' }).click()
  await expect(page.getByTestId('release-v1')).toContainText('Live')
  await page.screenshot({ path: out('07-studio-versions') })
  await page.getByRole('link', { name: 'Candidates' }).click()
  await expect(page.getByText('No candidates yet')).toBeVisible()
  await page.screenshot({ path: out('04-candidates-empty') })
  await page.getByRole('button', { name: 'Add candidate' }).first().click()
  await page.screenshot({ path: out('05-add-candidate') })
  await page.getByLabel(/Full name/).fill('Arjun Menon')
  await page.getByLabel(/^Email/).fill(`arjun.${run}@gmail.com`)
  await page.getByLabel(/^Phone/).fill('98450 12345')
  await page.getByRole('button', { name: /^Add candidate|^Save/ }).last().click()
  await page.waitForURL(/records\/candidate\/[0-9a-f-]{36}/)
  await expect(page.getByRole('heading', { name: 'Arjun Menon' })).toBeVisible()
  await page.screenshot({ path: out('06-candidate-profile') })
  await page.goto('/records/candidate')
  await expect(page.getByRole('link', { name: 'Arjun Menon' })).toBeVisible()
  await page.screenshot({ path: out('06b-candidates-list') })
  await page.goto('/activity')
  await expect(page.getByText(/candidate/i).first()).toBeVisible()
  await page.waitForTimeout(500)
  await page.screenshot({ path: out('08-activity') })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/records/candidate')
  await expect(page.getByText('Arjun Menon').first()).toBeVisible()
  await page.screenshot({ path: out('09-candidates-mobile') })
})
